"""Summary tables and Pareto plots from runs/final_exploration/results.csv, for docs/final_exploration/.

    uv run --extra explore experiments/final_exploration/summarize.py

Writes docs/final_exploration/results_summary.md (mean ± std over cv folds; val, size and stalkers
means), pareto_cv.png (SINDy terms vs whole-battle health nRMSE) and pareto_cv_margin.png (terms vs
margin R² at 4 s), plus a copy of the results table (results.csv) so the numbers are in git.
"""

import shutil

import numpy as np
import pandas as pd

from sindy_wm.evaluation import harness as H
from sindy_wm.paths import PROJECT_ROOT

DOCS = PROJECT_ROOT / "docs" / "final_exploration"
COLS = [
    "health_4s",
    "margin_r2_2s",
    "margin_r2_4s",
    "margin_r2_8s",
    "alive_4s",
    "distance_4s",
    "battle_health_nrmse",
    "winner_acc",
    "brier",
    "final_health_err",
    "duration_err_s",
    "blowup_rate",
    "n_terms",
]
SHORT = {
    "health_4s": "health 4s",
    "margin_r2_2s": "mR² 2s",
    "margin_r2_4s": "mR² 4s",
    "margin_r2_8s": "mR² 8s",
    "alive_4s": "alive 4s",
    "distance_4s": "dist 4s",
    "battle_health_nrmse": "battle nRMSE",
    "winner_acc": "winner",
    "brier": "Brier",
    "final_health_err": "final H err",
    "duration_err_s": "dur err s",
    "blowup_rate": "blow-up",
    "n_terms": "terms",
}


def fmt(mean, std=None, col=""):
    if pd.isna(mean):
        return ""
    d = 0 if col == "n_terms" else 3
    s = f"{mean:.{d}f}"
    if std is not None and not pd.isna(std) and col != "n_terms":
        s += f" ± {std:.{d}f}"
    return s


def table(split: str, with_std: bool) -> str:
    s = H.summarize(split=split, metrics=COLS)
    if s.empty:
        return "(no rows)\n"
    cols = [c for c in COLS if (c, "mean") in s]
    lines = ["| axis | experiment | " + " | ".join(SHORT[c] for c in cols) + " | folds |"]
    lines.append("|" + "---|" * (len(cols) + 3))
    for (axis, exp), row in s.iterrows():
        cells = [fmt(row[(c, "mean")], row[(c, "std")] if with_std else None, c) for c in cols]
        lines.append(f"| {axis} | {exp} | " + " | ".join(cells) + f" | {int(row[('folds', 'n')])} |")
    return "\n".join(lines) + "\n"


def main() -> None:
    DOCS.mkdir(parents=True, exist_ok=True)
    parts = [
        "# Final exploration: results summary (generated)\n",
        "Generated by `experiments/final_exploration/summarize.py` from `runs/final_exploration/results.csv`",
        "(copied to `docs/final_exploration/results.csv`). cv = mean ± std over the 5 folds of `train`.",
        "Do not edit by hand.\n",
        "Columns: health error and margin R² (mR²) at horizons from start points every 8th step; battle",
        "metrics from one rollout per battle from step 0; terms = SINDy terms (for J, network weights).\n",
    ]
    for split, std in (("cv", True), ("val", False), ("size", False), ("stalkers", False)):
        parts += [f"## {split}\n", table(split, std)]
    (DOCS / "results_summary.md").write_text("\n".join(parts))
    shutil.copy(H.RESULTS, DOCS / "results.csv")
    if H.COEFS.exists():
        shutil.copy(H.COEFS, DOCS / "coefficients.csv")
    import matplotlib

    matplotlib.use("Agg")
    H.pareto_plot("cv", "n_terms", "battle_health_nrmse", DOCS / "pareto_cv.png")
    fig = H.pareto_plot("cv", "n_terms", "margin_r2_4s")
    # higher is better for R²: redraw the front for "max"
    ax = fig.axes[0]
    for line in ax.lines[1:]:
        line.remove()
    s = H.summarize(split="cv", metrics=["n_terms", "margin_r2_4s"]).dropna()
    x, y = s[("n_terms", "mean")].to_numpy(), s[("margin_r2_4s", "mean")].to_numpy()
    front = [i for i in range(len(x)) if not any((x[j] <= x[i]) & (y[j] > y[i]) for j in range(len(x)))]
    order = sorted(front, key=lambda i: x[i])
    ax.plot(x[order], y[order], "-o", color="C0", ms=5, label="Pareto front")
    ax.set_ylim(max(-0.5, np.nanmin(y) - 0.05), None)
    fig.savefig(DOCS / "pareto_cv_margin.png", dpi=150)
    print("wrote", DOCS / "results_summary.md")


if __name__ == "__main__":
    main()
